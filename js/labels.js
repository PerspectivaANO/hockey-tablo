import { num } from "./format.js";

/**
 * Подписи вариантов в словаре продукта: «бросок», «шайбы», «множитель», «шанс»,
 * «граница». Слов «ставка», «коэффициент», «рынок», «тотал» здесь нет и не будет.
 * Набор вариантов зависит от формата: в 4х4 нет овертайма и буллитов, есть ничья.
 */
export function marketsFor(format, home, away, line) {
  const l = line === null || line === undefined ? "" : num(line);
  const overUnder = {
    title: `Сколько шайб забьют вдвоём · граница ${l}`,
    c: 2,
    opts: [["OV", `Больше ${l}`], ["UN", `Меньше ${l}`]],
  };
  if (format === "4x4") {
    return [
      { title: "Исход · в формате 4х4 овертайма нет", c: 3, opts: [["H", home], ["D", "Ничья"], ["A", away]] },
      overUnder,
      { title: "Разгром, 20 шайб разницы и больше", c: 2, opts: [["BH", home], ["BA", away]] },
      { title: "Обе команды забьют 10 и больше", c: 2, opts: [["BY", "Да"], ["BN", "Нет"]] },
    ];
  }
  return [
    { title: "Исход", c: 3, opts: [["H", home], ["T", "Овертайм или буллиты"], ["A", away]] },
    { title: "Победа в овертайме", c: 2, opts: [["OTH", home], ["OTA", away]] },
    { title: "Победа по буллитам", c: 2, opts: [["SOH", home], ["SOA", away]] },
    overUnder,
    { title: "Крупная победа, 3 шайбы и больше", c: 2, opts: [["BH", `${home} крупно`], ["BA", `${away} крупно`]] },
    { title: "Обе команды забьют", c: 2, opts: [["BY", "Да"], ["BN", "Нет"]] },
  ];
}

/** Короткая подпись варианта для списка бросков (граница в подписи не нужна). */
export function shortOption(key, home, away) {
  const t = {
    H: `Победа: ${home}`, A: `Победа: ${away}`, T: "Овертайм или буллиты", D: "Ничья",
    OTH: `Победа в овертайме: ${home}`, OTA: `Победа в овертайме: ${away}`,
    SOH: `Победа по буллитам: ${home}`, SOA: `Победа по буллитам: ${away}`,
    OV: "Шайб больше границы", UN: "Шайб меньше границы",
    BH: `Крупная победа: ${home}`, BA: `Крупная победа: ${away}`,
    BY: "Обе команды забьют", BN: "Одна из команд не забьёт",
  };
  return t[key] || key;
}

